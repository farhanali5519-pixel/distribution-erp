/**
 * On-Premise Customer Application Update Tool
 * 
 * Safely executes database migrations and updates without replacing customer data.
 * 1. Takes pre-update safety backup
 * 2. Runs pending migrations
 * 3. Verifies post-update database integrity
 * 4. Generates rollback instructions if needed
 */

import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import path from 'node:path';
import { BackupService } from '../src/lib/backup/backup-service.ts';
import { MigrationRunner } from '../src/core/database/migration-runner.ts';
import { APP_VERSION } from '../src/core/config/env.ts';

console.log('===================================================================');
console.log('       SaleFlow ERP — On-Premise Application Update Runner         ');
console.log('===================================================================\n');

const dbPath = path.join(process.cwd(), 'data', 'sales_distribution.db');

if (!fs.existsSync(dbPath)) {
  console.error(`[ERROR] Database not found at ${dbPath}`);
  process.exit(1);
}

// 1. Initial Database Pre-Check
console.log('[STEP 1/4] Checking live database integrity before update...');
const preDb = new DatabaseSync(dbPath);
const preCheck = preDb.prepare('PRAGMA integrity_check').get();
preDb.close();

if (preCheck?.integrity_check !== 'ok') {
  console.error(`[ERROR] Live database failed initial integrity check: ${preCheck?.integrity_check}`);
  console.error('Update aborted to protect customer data.');
  process.exit(1);
}
console.log('  -> Live database integrity is OK.\n');

// 2. Pre-Update Safety Backup
console.log('[STEP 2/4] Creating automated pre-update safety snapshot...');
const backupMeta = BackupService.createBackup('PRE_UPDATE');
console.log(`  -> Safety backup created: ${backupMeta.filename} (${backupMeta.sizeFormatted})`);
console.log(`  -> SHA-256 Checksum:     ${backupMeta.checksum}\n`);

// 3. Execute Pending Migrations
console.log('[STEP 3/4] Checking and executing pending database migrations...');
const migrationResult = MigrationRunner.runPendingMigrations();
if (migrationResult.appliedCount === 0) {
  console.log('  -> Database schema is already up to date. No pending migrations.\n');
} else {
  console.log(`  -> Applied ${migrationResult.appliedCount} migration(s): ${migrationResult.appliedVersions.join(', ')}\n`);
}

// 4. Post-Update Integrity Verification
console.log('[STEP 4/4] Verifying post-update database integrity...');
const postDb = new DatabaseSync(dbPath);
const postCheck = postDb.prepare('PRAGMA integrity_check').get();
const latestVersion = MigrationRunner.getLatestAppliedVersion(postDb);
postDb.close();

if (postCheck?.integrity_check !== 'ok') {
  console.error(`[CRITICAL] Post-update database integrity failed: ${postCheck?.integrity_check}`);
  console.error(`Please run "node scripts/rollback-update.mjs" to restore from ${backupMeta.filename}`);
  process.exit(1);
}

console.log('  -> Post-update integrity check passed (ok).\n');

// 5. Generate Rollback Script
const rollbackScriptContent = `/**
 * Rollback Script generated by onprem-update.mjs
 * Restores pre-update snapshot: ${backupMeta.filename}
 */
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const backupFile = path.join(process.cwd(), 'backups', '${backupMeta.filename}');
const targetDb = path.join(process.cwd(), 'data', 'sales_distribution.db');

console.log('Rolling back database from pre-update safety snapshot...');
if (!fs.existsSync(backupFile)) {
  console.error('Backup file not found:', backupFile);
  process.exit(1);
}

fs.copyFileSync(backupFile, targetDb);

const db = new DatabaseSync(targetDb);
const check = db.prepare('PRAGMA integrity_check').get();
db.close();

if (check?.integrity_check === 'ok') {
  console.log('Rollback successful! Database restored to pre-update state.');
} else {
  console.error('Rollback integrity check failed:', check);
}
`;

fs.writeFileSync(path.join(process.cwd(), 'scripts', 'rollback-update.mjs'), rollbackScriptContent);

console.log('===================================================================');
console.log(`[SUCCESS] SaleFlow ERP update completed successfully!`);
console.log(`  Target Application Version: v${APP_VERSION}`);
console.log(`  Database Schema Version:    v${latestVersion}`);
console.log(`  Safety Backup Snapshot:     ${backupMeta.filename}`);
console.log(`  Rollback Tool Ready:        scripts/rollback-update.mjs`);
console.log('===================================================================\n');
